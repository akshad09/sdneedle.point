export function normalizePalette(rawColors, id = "custom", label = "Custom palette") {
  return {
    id,
    label,
    note: "Imported custom palette.",
    colors: rawColors
      .map((row) => ({
        brand: label,
        number: String(row[0] ?? "").trim(),
        name: String(row[1] ?? "Unnamed").trim(),
        hex: normalizeHex(String(row[2] ?? "#000000").trim())
      }))
      .filter((color) => color.number && /^#[0-9a-f]{6}$/i.test(color.hex))
  };
}

export function getPalette(key) {
  const palette = PALETTES[key] || PALETTES.dmc;
  return normalizePalette(palette.colors, palette.id, palette.label);
}

function normalizeHex(value) {
  const trimmed = value.replace(/[^0-9a-f]/gi, "");
  if (trimmed.length === 3) {
    return `#${trimmed.split("").map((char) => char + char).join("")}`.toUpperCase();
  }
  if (trimmed.length >= 6) {
    return `#${trimmed.slice(0, 6)}`.toUpperCase();
  }
  return "#000000";
}
